"""A film's camera path from a rehearsal of it, smoothed (the user, 2026-11-09, of the staged scenes' fourth takes: "The
camera panning is super abrupt and not smooth at all"). A move that tracked the plugin's point "fight" (tests/lp-film-hooks)
followed it live: the point moved in steps each 6 ticks and jumped when units joined the fight or left it. A film is
deterministic, so its path can be known before it is shot: this rehearses the film headless with the point logged, smooths
the log (a Gaussian over SIGMA ticks, its speed held under VMAX), and writes params that play the path back as point "cam",
each move tracking it.

    uv run --with numpy scripts/film_smooth.py <visit profile> <save> <params.lua>
    then: scripts/film.sh <visit profile> <save> docs/sim/<name>-smooth.lua

Rehearsal and smoothed params go to docs/sim/ (not kept). A move on "fight" is put on "cam"; its zooms and timings stay,
and a move on a fixed point is left as it is.
"""
import os, subprocess, sys
import numpy as np

SIGMA = 100           # ticks: the smoothing's width (1.7 s)
VMAX = 0.09           # tiles a tick the camera may move (5.4 a second)
STEP = 2              # ticks between the path's samples
PAD = 360             # ticks either side of a move, its end points held, so its ends are smoothed as its middle

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
HOME = os.path.expanduser("~/Library/Application Support")


def lua_moves(params):
    """Each move's name, first tick, frames and every, and the film's fast_until, read by luajit from the params."""
    code = ('local P = dofile(%r) print("fast", P.fast_until or 0) '
            'for _, m in ipairs(P.moves or {}) do print(m.name, m.tick, m.frames, m.every or 2) end') % params
    out = subprocess.run(["luajit", "-e", code], capture_output=True, text=True, check=True).stdout.split("\n")
    fast = int(float(out[0].split()[1]))
    moves = [(n, int(t), int(f), int(e)) for n, t, f, e in (l.split() for l in out[1:] if l.strip())]
    return fast, moves


def wrap(params, extra):
    """Params that run the given ones and add to them (Lua: the file's body as a function)."""
    body = open(params).read()
    return ("-- Generated by scripts/film_smooth.py from %s: do not edit.\nlocal P = (function()\n%s\nend)()\n%s\nreturn P\n"
            % (os.path.relpath(params, REPO), body, extra))


def smooth(ts, xs, ys, t0, t1):
    # (Its own stretch of the log only, held at its ends: with the scene before it in its padding, a move began on the
    # last stage and crept to its own at VMAX.)
    grid = np.arange(t0, t1 + 1, STEP)
    lo, hi = grid[0] - PAD, grid[-1] + PAD
    keep = (ts >= t0) & (ts <= t1)
    if keep.sum() < 2:
        raise SystemExit("no fight points logged between ticks %d and %d" % (t0, t1))
    full = np.arange(lo, hi + 1, STEP)
    px, py = np.interp(full, ts[keep], xs[keep]), np.interp(full, ts[keep], ys[keep])
    k = np.arange(-3 * SIGMA, 3 * SIGMA + 1, STEP)
    w = np.exp(-0.5 * (k / SIGMA) ** 2); w /= w.sum()
    n = len(w) // 2
    sx = np.convolve(np.pad(px, n, mode="edge"), w, mode="valid")
    sy = np.convolve(np.pad(py, n, mode="edge"), w, mode="valid")
    # Its speed held under VMAX: each step no longer than VMAX * STEP toward where the smoothed path is.
    cx, cy = [sx[0]], [sy[0]]
    for x, y in zip(sx[1:], sy[1:]):
        dx, dy = x - cx[-1], y - cy[-1]
        d = (dx * dx + dy * dy) ** 0.5
        f = min(1.0, VMAX * STEP / d) if d > 0 else 1.0
        cx.append(cx[-1] + dx * f); cy.append(cy[-1] + dy * f)
    # (Held at VMAX, it started and stopped at once where the cap took over: smoothed again, a third as wide.)
    w2 = np.exp(-0.5 * (k / (SIGMA / 3)) ** 2); w2 /= w2.sum()
    cx = np.convolve(np.pad(np.array(cx), n, mode="edge"), w2, mode="valid")
    cy = np.convolve(np.pad(np.array(cy), n, mode="edge"), w2, mode="valid")
    i0 = int((grid[0] - lo) / STEP)
    return grid[0], cx[i0:i0 + len(grid)], cy[i0:i0 + len(grid)]


def main():
    if len(sys.argv) != 4:
        raise SystemExit(__doc__)
    profile, save, params = sys.argv[1], sys.argv[2], os.path.abspath(sys.argv[3])
    name = os.path.splitext(os.path.basename(params))[0]
    fast, moves = lua_moves(params)
    end = max(t + f * e for _, t, f, e in moves)
    out_dir = os.path.join(REPO, "docs", "sim")
    log = os.path.join(HOME, "factorio-lp-visit", profile, "script-output", "lp-film-fight.txt")
    if os.path.exists(log):
        os.remove(log)
    rehearse = os.path.join(out_dir, name + "-rehearse.lua")
    # (Its name kept: film.sh reads it from the file to find the helper's output.)
    open(rehearse, "w").write(wrap(params, 'P.fight, P.fight_log = true, true'))
    env = dict(os.environ, FILM_REHEARSE=str(end - fast + PAD + 1200))
    subprocess.run([os.path.join(REPO, "scripts", "film.sh"), profile, save, rehearse,
                    os.path.join(out_dir, "film-" + name + "-rehearse")], env=env, check=True, stdout=subprocess.DEVNULL)
    if not os.path.exists(log):
        raise SystemExit("the rehearsal wrote no fight points (%s): is fight = true and the plugin installed?" % log)
    a = np.loadtxt(log)
    ts, xs, ys = a[:, 0], a[:, 1], a[:, 2]
    segs = []
    for mname, t, f, e in moves:
        t0, cx, cy = smooth(ts, xs, ys, t, t + f * e)
        xy = ", ".join("%.2f, %.2f" % (x, y) for x, y in zip(cx, cy))
        segs.append("  {t0 = %d, every = %d, xy = {%s}}," % (t0, STEP, xy))
        jumps = np.hypot(np.diff(cx), np.diff(cy)).max() / STEP
        print("%s: %d samples, fastest %.3f tiles a tick" % (mname, len(cx), jumps))
    extra = ("P.fight = true\nP.path = {\n%s\n}\n"
             "for _, m in ipairs(P.moves) do if m.from.pos == \"fight\" then m.from.pos = \"cam\" end end" % "\n".join(segs))
    smooth_params = os.path.join(out_dir, name + "-smooth.lua")
    open(smooth_params, "w").write(wrap(params, extra))
    print("film it: scripts/film.sh %s %s %s" % (profile, save, os.path.relpath(smooth_params, REPO)))


if __name__ == "__main__":
    main()
