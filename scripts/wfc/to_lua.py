"""Turn a .tiles file into the mod's tile table: every variant (turned, mirrored) with its rows, its weight and, for each
side, the variants that may stand there (computed here, once, with the same rule as wfc.py).

    python3 -I scripts/wfc/to_lua.py scripts/wfc/serenity.tiles landing-party/scripts/wfc_serenity.lua
"""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import wfc

def main():
    src, out = sys.argv[1], sys.argv[2]
    tiles = wfc.parse(src)
    errs = [e for t in tiles for e in wfc.check_tile(t)]
    if errs: print("\n".join(errs)); sys.exit(1)
    vs = wfc.variants(tiles)
    cm = wfc.compat(vs)
    L = ["-- Generated by scripts/wfc/to_lua.py from " + os.path.basename(src) + ": do not edit; edit the .tiles file.",
         "return {size = %d, variants = {" % wfc.SIZE]
    for i, v in enumerate(vs):
        rows = ", ".join('"%s"' % r for r in v["rows"])
        fit = ", ".join("%s = {%s}" % (d, ", ".join(str(j + 1) for j in sorted(cm[(i, d)]))) for d in "nsew")
        L.append('  {name = "%s", weight = %g, rows = {%s}, fit = {%s}},' % (v["name"], v["w"], rows, fit))
    L.append("}}")
    open(out, "w").write("\n".join(L) + "\n")
    print(f"{out}: {len(vs)} variants")

if __name__ == "__main__":
    main()
