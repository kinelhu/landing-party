"""Armed units' prior prices for Synthexis (landing-party/scripts/unit_prior.lua), from the arena's balance table
(docs/arena/results.jsonl, scripts/arena.sh): each unit kind fought bred mediums at equal spend; its price is the mediums
it killed per unit, the mean of its rounds. A unit that won lost none of its own: what it killed was all there was, a
least. Rerun after scripts/arena.sh.
    uv run python3 -I scripts/unit_prior.py
"""
import json
import os
import re

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
batch = open(os.path.join(root, "tests/lp-arena/batch.lua")).read()
kinds = dict(re.findall(r'\{"([^"]+)", "(lp-[a-z-]+)"', batch.split("local KINDS", 1)[1].split("}\n\n", 1)[0]))
rows = [json.loads(l) for l in open(os.path.join(root, "docs/arena/results.jsonl")) if l.strip()]
kills = {}
for r in rows:
    if r.get("kind") == "pair" and r.get("against") == "bred medium" and r["squad"] in kinds:
        kills.setdefault(kinds[r["squad"]], []).append(r["b"]["lost"].get("unit", 0) / max(1, r["a"]["start"]))
out = ["-- Generated by scripts/unit_prior.py from docs/arena/results.jsonl: an armed unit's price to Synthexis before it has",
       "-- learned one (threat.prior_of): the bred mediums it killed per unit in the arena, at equal spend. Do not edit.",
       "return {"]
for name in sorted(kills):
    if not name.startswith("lp-bred-") and name != "lp-runt":
        v = kills[name]
        out.append(f'  ["{name}"] = {sum(v) / len(v):.2f},')
out.append("}")
open(os.path.join(root, "landing-party/scripts/unit_prior.lua"), "w").write("\n".join(out) + "\n")
print("\n".join(out))
